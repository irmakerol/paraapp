// Builds supabase/seed.sql from the Markdown drafts in docs/legal.
// Run with `node scripts/gen-legal-seed.mjs` after editing a legal text, and bump VERSION
// when a change is material (users are asked to accept/acknowledge again).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = 1;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const docs = [
  ['privacy_notice', 'tr', 'Aydınlatma Metni'],
  ['privacy_notice', 'en', 'Privacy Notice'],
  ['terms', 'tr', 'Kullanım Koşulları'],
  ['terms', 'en', 'Terms of Use'],
  ['explicit_consent', 'tr', 'Açık Rıza Metni'],
  ['explicit_consent', 'en', 'Explicit Consent'],
];

const quote = (s) => `$legal$${s}$legal$`;
const rows = docs.map(([kind, locale, title]) => {
  const body = readFileSync(join(root, 'docs/legal', `${kind}.${locale}.md`), 'utf8');
  return `  ('${kind}', '${locale}', ${VERSION}, ${quote(title)}, ${quote(body)}, now())`;
});

const sql = `-- Generated by scripts/gen-legal-seed.mjs from docs/legal/*.md. Do not edit by hand.
-- Development seed. Legal texts are DRAFTS until reviewed by the club's lawyer.

insert into public.legal_documents (kind, locale, version, title, body_md, published_at) values
${rows.join(',\n')}
on conflict (kind, locale, version) do update
  set title = excluded.title, body_md = excluded.body_md;
`;
writeFileSync(join(root, 'supabase/seed.sql'), sql);
console.log('wrote supabase/seed.sql');
